import { HandledError, logger } from '@redocly/openapi-core';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

import { type CommandArgs } from '../wrapper.js';
import { ejectAssetsDir } from './eject-generator.js';

export type ScaffoldGeneratorCommandArgv = {
  generator?: string;
  config?: string;
  dir?: string;
};

const BUILTIN_NAMES = new Set([
  'sdk',
  'zod',
  'tanstack-query',
  'tanstack-query-vue',
  'tanstack-query-svelte',
  'tanstack-query-solid',
  'swr',
  'transformers',
  'mock',
  'cli',
  'python',
  'go',
  'php',
]);

function skeleton(name: string): string {
  return `// A custom generator scaffolded by \`redocly scaffold-generator\`.
// It runs from the \`generators\` list in redocly.yaml and emits files next to the
// configured client output. The authoring guide for your agent is in ./AGENTS.md;
// the deep reference is the "Customize client generation" guide in the Redocly docs.
import { CodeWriter, identifierFor } from '@redocly/client-generator';

export default {
  name: '${name}',

  /**
   * @param {{ model: import('@redocly/client-generator').ApiModel, outputPath: string }} input
   * @returns {{ path: string, content: string }[]}
   */
  run({ model, outputPath }) {
    const writer = new CodeWriter('  ');
    writer.line(\`// \${model.title} \${model.version} — generated by the "${name}" generator.\`);
    for (const service of model.services) {
      for (const op of service.operations) {
        // Every operation of the API description; \`op.name\` is a sanitized identifier,
        // \`op.pathParams\`/\`op.queryParams\`/\`op.requestBody\` describe its inputs.
        writer.line(\`// \${op.method.toUpperCase()} \${op.path} — \${identifierFor(op.name)}\`);
      }
    }
    return [{ path: outputPath.replace(/\\.[^.]+$/, '.${name}.txt'), content: writer.toString() }];
  },
};
`;
}

export const handleScaffoldGenerator = async ({
  argv,
}: CommandArgs<ScaffoldGeneratorCommandArgv>) => {
  const name = argv.generator ?? '';
  if (!/^[a-z][a-z0-9-]*$/.test(name)) {
    throw new HandledError(
      `\n❌  Generator name must be kebab-case (got "${name}"). Example: redocly scaffold-generator route-map\n`
    );
  }
  if (BUILTIN_NAMES.has(name)) {
    throw new HandledError(
      `\n❌  "${name}" is a built-in generator — use \`redocly eject-generator ${name}\` to vendor it, or pick another name.\n`
    );
  }
  const dir = resolve(argv.dir ?? './generators');
  const target = join(dir, `${name}.mjs`);
  if (existsSync(target)) {
    throw new HandledError(`\n❌  ${relative(process.cwd(), target)} already exists.\n`);
  }
  mkdirSync(dir, { recursive: true });
  writeFileSync(target, skeleton(name), 'utf-8');

  // The same AGENTS.md drop the eject command performs (markers keep user additions safe).
  const template = readFileSync(join(ejectAssetsDir(), 'AGENTS.md'), 'utf-8').trim();
  const agents = join(dir, 'AGENTS.md');
  if (!existsSync(agents)) {
    writeFileSync(
      agents,
      `<!-- redocly-generators:begin — managed by \`redocly eject-generator\`; content between markers is refreshed on eject -->\n\n${template}\n\n<!-- redocly-generators:end -->\n`,
      'utf-8'
    );
  }

  const configPath = `./${relative(process.cwd(), target).split('\\').join('/')}`;
  logger.info(
    `Scaffolded ${relative(process.cwd(), target)}.\n` +
      `Add it to your config and run \`redocly generate-client\`:\n\n` +
      `  client:\n    generators:\n      - sdk\n      - ${configPath}\n`
  );
};
