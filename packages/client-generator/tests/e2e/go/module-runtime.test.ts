import { generateClient } from '@redocly/client-generator';
import { spawnSync } from 'node:child_process';
import { readFileSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { copyConsumer } from '../helpers/helpers.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const fixture = join(__dirname, '../fixtures/cafe.yaml');

describe('generate-client --runtime module, go', () => {
  let dir = '';

  beforeAll(async () => {
    dir = copyConsumer(join(__dirname, 'consumer-module-runtime'));
    await generateClient({
      api: fixture,
      output: join(dir, 'client.ts'),
      generators: ['go'],
      runtime: 'module',
    });
  });

  afterAll(() => {
    rmSync(dir, { recursive: true, force: true });
  });

  it(
    'the client and runtime.go build as one package',
    () => {
      const runtime = readFileSync(join(dir, 'runtime.go'), 'utf-8');
      expect(runtime.startsWith('// Generated by @redocly/client-generator')).toBe(true);
      const result = spawnSync('go', ['build', './...'], { cwd: dir, encoding: 'utf-8' });
      expect(result.status, result.stderr).toBe(0);
    },
    // A cold CI cache compiles the stdlib on the first build.
    180_000
  );
});
