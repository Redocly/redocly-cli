import { generateClient } from '@redocly/client-generator';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { expectJavacPasses } from './javac.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const fixture = join(__dirname, '../fixtures/cafe.yaml');

describe('generate-client --runtime module, java', () => {
  let dir = '';

  beforeAll(async () => {
    dir = mkdtempSync(join(tmpdir(), 'module-runtime-java-'));
    await generateClient({
      api: fixture,
      output: join(dir, 'client.ts'),
      generators: ['java'],
      runtime: 'module',
    });
  });

  afterAll(() => {
    rmSync(dir, { recursive: true, force: true });
  });

  it(
    'the client extends the runtime class, and both files compile together',
    () => {
      const runtime = readFileSync(join(dir, 'ClientRuntime.java'), 'utf-8');
      expect(runtime.startsWith('// Generated by @redocly/client-generator')).toBe(true);
      expect(runtime).toContain('public abstract class ClientRuntime {');
      expect(readFileSync(join(dir, 'Client.java'), 'utf-8')).toContain(
        'public final class Client extends ClientRuntime {'
      );
      expectJavacPasses(dir, ['Client.java', 'ClientRuntime.java']);
    },
    // javac starts a JVM, and a cold CI runner takes its time over that.
    180_000
  );
});
