// The built-in `java` generator — the fourth non-TypeScript library entry, authored
// with the language-neutral toolkit only (same dogfooding invariant as python/go/php,
// pinned by the guard test). Output is one Java >= 17 file over java.net.http: a public
// class named after the output stem that nests the records (with fromJson/toJson
// hydration), wire-backed enums, sealed union interfaces, the embedded runtime, and one
// typed method per operation. Exceptions are the error mode (`errorMode` does not apply).

import {
  type CodeSample,
  type Generator,
  type GeneratorOptionsSchema,
  identifierFor,
  jsonSuccessSchema,
  type NeutralPaginationRule,
  type OperationModel,
  renderReferencePage,
  type SampleContext,
  sseResponse,
} from '@redocly/client-generator';
import { JavaPrinter } from '@redocly/client-generator/printers/java';
import { JAVA_RUNTIME_SOURCE } from '@redocly/client-generator/runtime-sources';

import { writeServers } from './client.ts';
import { writeJavaModels } from './models.ts';
import { JAVA, javaClassName, javaPackageName, javaString, methodIdents } from './naming.ts';
import { paramsClassName, writeJavaMethod, writeParamsClass } from './operations.ts';
import { writeJavaPaginationWrappers } from './pagination.ts';
import { javaType } from './types.ts';

export { renderJavaModels } from './models.ts';
export { javaType } from './types.ts';

export const javaOptions: GeneratorOptionsSchema = {
  type: 'object',
  properties: {
    package: {
      type: 'string',
      description:
        'The package clause of the generated file, for example `com.example.api`. Absent, the class is in the default package.',
    },
  },
};

/** The `import` lines of the runtime, which the generated file declares for both of them. */
function runtimeImports(): string[] {
  return JAVA_RUNTIME_SOURCE.split('\n').filter((line) => line.startsWith('import '));
}

/**
 * The runtime's class body — everything between its class line and its closing brace, at
 * the one-level indent the generated class also uses — for inline embedding.
 */
function runtimeBody(): string[] {
  const lines = JAVA_RUNTIME_SOURCE.split('\n');
  const start = lines.findIndex((line) => line.startsWith('abstract class Runtime {'));
  const end = lines.lastIndexOf('}');
  return lines
    .slice(start + 1, end)
    .map((line) => (line.startsWith('    ') ? line.slice(4) : line));
}

/** The whole generated file: package, imports, and the class nesting models, runtime, and methods. */
export const javaGenerator: Generator = ({ model, output, banner, emit, pagination, options }) => {
  const printer = new JavaPrinter();
  const dateType = emit.dateType ?? 'string';
  const className = javaClassName(output.stem, model);
  const packageName = javaPackageName(options?.package);
  const moduleRuntime = emit.runtime === 'module';
  const runtimeClass = `${className}Runtime`;
  const operations = model.services.flatMap((service) => service.operations);
  const idents = methodIdents(model);
  // Pagination arrives RESOLVED from the pipeline — one fit-verified answer per run.
  const paginationRules = new Map<string, NeutralPaginationRule>();
  for (const op of operations) {
    const spec = pagination?.get(op.name)?.spec;
    if (spec !== undefined) paginationRules.set(op.name, spec);
  }

  printer.line(
    `// Code generated by @redocly/client-generator (java) from ${javaString(model.title)} ${model.version}. DO NOT EDIT.`
  );
  printer.line(
    '// Regenerate with `redocly generate-client`. Java >= 17, standard library only — zero dependencies.'
  );
  printer.blank();
  if (packageName !== undefined) {
    printer.line(`package ${packageName};`);
    printer.blank();
  }
  for (const line of runtimeImports()) printer.line(line);
  printer.blank();
  printer.doc(className, `Client for ${model.title} (${model.version}).`);
  printer.block(
    `public final class ${className}${moduleRuntime ? ` extends ${runtimeClass}` : ''} {`,
    () => {
      writeJavaModels(printer, model, dateType);
      writeServers(printer, model);
      if (!moduleRuntime) {
        printer.line('// ─── Embedded runtime (@redocly/client-generator java runtime) ───');
        for (const line of runtimeBody()) printer.line(line);
        printer.blank();
      }
      for (const op of operations) {
        writeParamsClass(printer, op, idents.get(op.name)!, model, dateType);
      }
      printer.line('private final Config config;');
      printer.blank();
      printer.block(
        `public ${className}(Config config) {`,
        () => {
          printer.line('this.config = config;');
          printer.block(
            'if (config.serverUrl.isEmpty()) {',
            () => {
              printer.line(
                `config.serverUrl = ${javaString(emit.serverUrl ?? model.serverUrl ?? '')};`
              );
            },
            '}'
          );
        },
        '}'
      );
      printer.blank();
      printer.block(
        `public ${className}() {`,
        () => {
          printer.line('this(new Config());');
        },
        '}'
      );
      printer.blank();

      for (const op of operations) {
        const ident = idents.get(op.name)!;
        const rule = paginationRules.get(op.name);
        writeJavaMethod(printer, op, ident, model, dateType, rule);
        if (sseResponse(op) === undefined && (op.successResponseHeaders?.length ?? 0) > 0) {
          writeJavaMethod(printer, op, ident, model, dateType, rule, true);
        }
        if (rule !== undefined) {
          writeJavaPaginationWrappers(printer, op, ident, model, dateType, rule);
        }
      }
    },
    '}'
  );

  const entry = {
    path: output.path.replace(/[^\\/]+$/, `${className}.java`),
    content: printer.toString(),
  };
  if (!moduleRuntime) return [entry];
  // The runtime as a real file: the same source, as a public base class the client extends,
  // so every runtime name resolves unqualified in both runtime modes.
  const header = banner.map((line) => `// ${line}`).join('\n');
  const runtimeSource = JAVA_RUNTIME_SOURCE.replace(
    /^abstract class Runtime \{$/m,
    `public abstract class ${runtimeClass} {`
  );
  const packageClause = packageName === undefined ? '' : `package ${packageName};\n\n`;
  return [
    entry,
    {
      path: output.path.replace(/[^\\/]+$/, `${runtimeClass}.java`),
      content: `${header}\n${packageClause}${runtimeSource
        .replace(/^\/\/.*\n/gm, '')
        .trimStart()
        .trimEnd()}\n`,
    },
  ];
};

/** One idiomatic Java call per operation — feeds `x-codeSamples` for docs. */
export function javaSample(op: OperationModel, ctx: SampleContext): CodeSample {
  const dateType = ctx.emit.dateType ?? 'string';
  const stem = ctx.outputPath.replace(/^.*[\\/]/, '').replace(/\.[^.]+$/, '');
  const className = identifierFor(stem, { style: 'pascal', reserved: JAVA }) || 'Client';
  const ident = methodIdents(ctx.model).get(op.name) ?? identifierFor(op.name, { reserved: JAVA });
  const args = [
    ...op.pathParams.map((param) =>
      javaString(`<${identifierFor(param.name, { reserved: JAVA })}>`)
    ),
    ...(op.requestBody ? ['body'] : []),
    ...(paramsClassName(op, ident, ctx.model) === undefined
      ? []
      : [`new ${className}.${paramsClassName(op, ident, ctx.model)}()`]),
  ];
  const call = `client.${ident}(${args.join(', ')})`;
  // The statement matches the return shape: a void method has no result, an SSE method is
  // iterated, and a typed method binds its result.
  const statement =
    sseResponse(op) !== undefined
      ? `for (var event : ${call}) {\n    System.out.println(event.data());\n}`
      : jsonSuccessSchema(op) === undefined
        ? `${call};`
        : `${javaType(jsonSuccessSchema(op)!, ctx.model, dateType)} result = ${call};`;
  return {
    lang: 'java',
    label: 'Java SDK',
    source: `${className} client = new ${className}(new ${className}.Config());\n${statement}\n`,
  };
}

/**
 * The SDK's own reference page, written when `client.docs` is on. The call snippets come
 * from `javaSample` — this generator's own hook — so the page can only ever show the syntax
 * of the SDK beside it, and ejecting this generator takes the page with it.
 */
export const javaDocs: Generator = ({ model, output, emit, pagination }) => [
  {
    path: output.path.replace(/\.[^.\\/]+$/, '.java.md'),
    content: renderReferencePage(model, {
      title: `${model.title} Java SDK reference`,
      frontmatter: emit.docsFrontmatter === true,
      language: {
        name: 'java',
        label: 'Java',
        fence: 'java',
        requires: 'The SDK needs Java 17 or newer and the standard library only.',
      },
      sample: (op) => javaSample(op, { model, emit, outputPath: output.path }),
      paginated: new Set(pagination?.keys() ?? []),
    }),
  },
];
