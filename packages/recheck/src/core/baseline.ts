import * as yaml from 'js-yaml';
import * as path from 'path';

import type { Problem } from '../types/index.js';
import { isPlainObject } from '../utils/is-plain-object.js';

/** A count for a Markdown page, or the JSON pointers of an API description's errors. */
type BaselineEntry = number | string[];

/** Parsed baseline file: an entry per config-relative file per rule. */
export interface BaselineFile {
  version: 1;
  files: Record<string, Record<string, BaselineEntry>>;
}

export interface BaselineComparison {
  /** Problems to report: non-errors, over-budget groups, and stale entries. */
  problems: Problem[];
  /** Error findings hidden because their (file, rule) count or pointer matches the baseline. */
  suppressed: number;
  /** Error findings in groups that exceed their baselined count, or at an unlisted pointer. */
  newFindings: number;
  /** Counts that exceed what this run found, and listed pointers with no finding. */
  staleEntries: number;
}

const GENERATED_HEADER = '# Generated by `redocly recheck --generate-baseline`.\n';

export function parseBaseline(content: string, sourcePath: string): BaselineFile {
  const raw = yaml.load(content);
  if (!isPlainObject(raw)) {
    throw new Error(`baseline file ${sourcePath} must be a YAML mapping`);
  }
  const { version, files } = raw;
  if (version !== 1) {
    throw new Error(`baseline file ${sourcePath} has unsupported version ${String(version)}`);
  }
  const parsed: BaselineFile = { version: 1, files: {} };
  if (files === undefined || files === null) return parsed;
  if (!isPlainObject(files)) {
    throw new Error(`baseline file ${sourcePath}: "files" must be a mapping`);
  }
  for (const [file, rules] of Object.entries(files)) {
    if (!isPlainObject(rules)) {
      throw new Error(
        `baseline file ${sourcePath}: entry "${file}" must map rules to counts or pointers`
      );
    }
    const entries: Record<string, BaselineEntry> = {};
    for (const [rule, entry] of Object.entries(rules)) {
      if (typeof entry === 'number' && Number.isInteger(entry) && entry > 0) {
        entries[rule] = entry;
      } else if (
        Array.isArray(entry) &&
        entry.length > 0 &&
        entry.every((pointer) => typeof pointer === 'string' && pointer.startsWith('#/'))
      ) {
        entries[rule] = [...new Set<string>(entry)];
      } else {
        throw new Error(
          `baseline file ${sourcePath}: "${file}" / "${rule}" must be a positive integer or a non-empty list of JSON pointers starting with "#/"`
        );
      }
    }
    parsed.files[file] = entries;
  }
  return parsed;
}

/** Builds a baseline from the error findings. `toKey` gives the file name stored in the baseline. */
export function buildBaseline(problems: Problem[], toKey: (file: string) => string): BaselineFile {
  // No prototype, so a file or rule named `__proto__` is an ordinary key.
  const files: Record<string, Record<string, BaselineEntry>> = Object.create(null);
  for (const { key, rule, problems: errors } of groupErrors(problems, toKey).values()) {
    const rules: Record<string, BaselineEntry> = (files[key] ??= Object.create(null));
    // A group with a page error, which has no pointer, keeps a count.
    const pointers = errors.map((error) => error.pointer);
    rules[rule] = pointers.every((pointer): pointer is string => pointer !== undefined)
      ? [...new Set(pointers)]
      : errors.length;
  }
  return { version: 1, files };
}

/** Writes the baseline with sorted keys, so unchanged input gives identical output. */
export function serializeBaseline(baseline: BaselineFile): string {
  const files: Record<string, Record<string, BaselineEntry>> = {};
  for (const file of Object.keys(baseline.files).sort()) {
    const rules: Record<string, BaselineEntry> = {};
    for (const rule of Object.keys(baseline.files[file]).sort()) {
      const entry = baseline.files[file][rule];
      rules[rule] = typeof entry === 'number' ? entry : [...entry].sort();
    }
    files[file] = rules;
  }
  return GENERATED_HEADER + yaml.dump({ version: 1, files }, { sortKeys: false });
}

export interface CompareOptions {
  /** Files this run scanned, in the Problem.file form. */
  scannedFiles: string[];
  /** Rule names (full config keys) that actually ran. */
  executedRules: Set<string>;
  /** Maps a Problem.file to the config-relative key the baseline stores. */
  toKey: (file: string) => string;
  /**
   * Config-relative folders that were fully scanned. Baseline entries under them count as
   * seen even if the file was deleted, so they turn stale. Leave unset for `--changed-only`.
   */
  scanRoots?: string[];
  /** Baseline keys of files this run could not read; their entries are neither matched nor stale. */
  skipFiles?: Set<string>;
  /**
   * The descriptions this run linted, as `<baseline key>\0<pointer>`, and the description rules
   * that ran. A pointer entry is stale only when its rule linted its description without an error.
   */
  lintedDescriptions?: { pointers: Set<string>; rules: Set<string> };
}

function underRoot(key: string, root: string): boolean {
  if (root === '' || root === '.') return true;
  return key === root || key.startsWith(`${root}/`);
}

function groupErrors(problems: Problem[], toKey: (file: string) => string) {
  const groups = new Map<string, { key: string; rule: string; problems: Problem[] }>();
  for (const problem of problems) {
    if (problem.severity !== 'error') continue;
    const key = toKey(problem.file);
    const groupId = `${key}\0${problem.ruleName}`;
    const group = groups.get(groupId) ?? { key, rule: problem.ruleName, problems: [] };
    group.problems.push(problem);
    groups.set(groupId, group);
  }
  return groups;
}

/**
 * Applies the baseline to the problems. Only errors are affected. An entry is checked for
 * staleness only if its file was scanned and its rule ran, so `--rule`, `--changed-only` and
 * narrower paths do not cause false alarms.
 */
export function compareToBaseline(
  problems: Problem[],
  baseline: BaselineFile,
  options: CompareOptions
): BaselineComparison {
  const kept = problems.filter((problem) => problem.severity !== 'error');
  let suppressed = 0;
  let newFindings = 0;

  const errorGroups = groupErrors(problems, options.toKey);
  for (const group of errorGroups.values()) {
    const entry = options.skipFiles?.has(group.key)
      ? undefined
      : baseline.files[group.key]?.[group.rule];
    if (Array.isArray(entry)) {
      for (const problem of group.problems) {
        if (problem.pointer !== undefined && entry.includes(problem.pointer)) {
          suppressed++;
        } else {
          newFindings++;
          kept.push(problem);
        }
      }
      continue;
    }
    const budget = entry ?? 0;
    const found = group.problems.length;
    if (found <= budget) {
      suppressed += found;
      continue;
    }
    newFindings += found - budget;
    for (const problem of group.problems) {
      kept.push(
        budget === 0
          ? problem
          : {
              ...problem,
              message: `${problem.message} (baseline ${budget}, found ${found})`,
            }
      );
    }
  }

  // A file counts as seen if it was scanned, or if it is under a fully scanned folder
  // and was not found (a deleted file).
  const scannedKeys = new Set(options.scannedFiles.map(options.toKey));
  const staleProblems: Problem[] = [];
  for (const [file, rules] of Object.entries(baseline.files)) {
    if (options.skipFiles?.has(file)) continue;
    const seen =
      scannedKeys.has(file) || (options.scanRoots ?? []).some((root) => underRoot(file, root));
    for (const [rule, entry] of Object.entries(rules)) {
      const groupId = `${file}\0${rule}`;
      const foundProblems = errorGroups.get(groupId)?.problems ?? [];
      if (Array.isArray(entry)) {
        const linted = options.lintedDescriptions;
        if (!linted?.rules.has(rule)) continue;
        const foundPointers = new Set(foundProblems.map((problem) => problem.pointer));
        for (const pointer of entry) {
          if (foundPointers.has(pointer) || !linted.pointers.has(`${file}\0${pointer}`)) continue;
          staleProblems.push({
            file,
            pointer,
            line: 1,
            column: 1,
            text: '',
            match: '',
            ruleName: rule,
            severity: 'error',
            message: `Baseline is stale: no finding of ${rule} at ${pointer}. Remove the pointer from the baseline or regenerate it.`,
          });
        }
        continue;
      }
      if (!seen || !options.executedRules.has(rule)) continue;
      const budget = entry;
      const found = foundProblems.length;
      if (found >= budget) continue;
      staleProblems.push({
        file,
        line: 1,
        column: 1,
        text: '',
        match: '',
        ruleName: rule,
        severity: 'error',
        message:
          `Baseline is stale: expected ${budget} finding(s) of ${rule}, found ${found}. ` +
          `Run \`redocly recheck --generate-baseline\` and commit the result.`,
      });
    }
  }

  return {
    problems: [...kept, ...staleProblems],
    suppressed,
    newFindings,
    staleEntries: staleProblems.length,
  };
}

/** The config-relative key mapper both `run` and `baseline` share. */
export function baselineKeyMapper(configDir: string): (file: string) => string {
  return (file: string) => path.relative(configDir, path.resolve(file)).split(path.sep).join('/');
}
