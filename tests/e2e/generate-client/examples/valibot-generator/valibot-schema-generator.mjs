// A custom generator that emits Valibot schemas, one per named schema in the description.
//
// It exists to answer a question people ask about every code generator: "you support the
// validation library I don't use — now what?" The answer is this file. It is ~60 lines over
// the authoring toolkit, it ships no new dependency into the generated client, and nothing
// in it is privileged: the built-in `zod` generator is the same shape, only longer.
//
// Plain ESM so the CLI imports it under bare `node`. In TypeScript you would write:
//
//   import { defineGenerator, flattenAllOf, enumValues } from '@redocly/client-generator';
//   export default defineGenerator({ name: 'valibot', run({ model, output }) { … } });
//
// `defineGenerator` only supplies types, so a plain object works the same.
import { enumValues, flattenAllOf, Printer } from '@redocly/client-generator';

/** A schema from the API model, as a Valibot expression. */
function valibotSchema(schema, model) {
  const asEnum = enumValues(schema);
  if (asEnum !== undefined) {
    return `v.picklist([${asEnum.values.map((value) => JSON.stringify(value)).join(', ')}])`;
  }
  switch (schema.kind) {
    case 'scalar':
      if (schema.scalar === 'integer' || schema.scalar === 'number') return 'v.number()';
      if (schema.scalar === 'boolean') return 'v.boolean()';
      // `format` rides on the schema metadata, so a generator can follow the same
      // decisions the built-in generators make. `binary` is a `Blob` in the client, and a
      // schema that called it a string would disagree with the type on every call site.
      if (schema.metadata?.format === 'binary') return 'v.blob()';
      return 'v.string()';
    case 'literal':
      return `v.literal(${JSON.stringify(schema.value)})`;
    case 'array':
      return `v.array(${valibotSchema(schema.items, model)})`;
    case 'record':
      return `v.record(v.string(), ${valibotSchema(schema.value, model)})`;
    // A reference points at another emitted schema; `v.lazy` keeps a recursive one legal.
    case 'ref':
      return `v.lazy(() => ${schema.name}Schema)`;
    case 'union':
      return `v.union([${schema.members.map((member) => valibotSchema(member, model)).join(', ')}])`;
    case 'null':
      return 'v.null()';
    case 'object':
    case 'intersection': {
      // `flattenAllOf` merges an allOf composition into one property list, so this
      // generator never implements composition semantics itself.
      const flat = flattenAllOf(schema, model) ?? { properties: schema.properties ?? [] };
      const entries = flat.properties.map((property) => {
        const inner = valibotSchema(property.schema, model);
        const value = property.required ? inner : `v.optional(${inner})`;
        return `  ${JSON.stringify(property.name)}: ${value},`;
      });
      return entries.length === 0 ? 'v.object({})' : `v.object({\n${entries.join('\n')}\n})`;
    }
    default:
      return 'v.unknown()';
  }
}

export default {
  name: 'valibot',
  run({ model, output }) {
    const printer = new Printer();
    printer.line('// Generated by the valibot custom generator. Do not edit by hand.');
    printer.line("import * as v from 'valibot';");
    printer.blank();
    for (const { name, schema } of model.schemas) {
      printer.line(`export const ${name}Schema = ${valibotSchema(schema, model)};`);
      printer.line(`export type ${name} = v.InferOutput<typeof ${name}Schema>;`);
      printer.blank();
    }
    return [{ path: output.path.replace(/\.ts$/, '.valibot.ts'), content: printer.toString() }];
  },
};
