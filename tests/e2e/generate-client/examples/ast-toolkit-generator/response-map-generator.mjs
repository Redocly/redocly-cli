// A custom generator that renders real TypeScript TYPES with the
// `@redocly/client-generator/generate` text toolkit — `tsType` is the same
// schema→type renderer the built-in sdk uses (refs, arrays, unions, formats,
// parenthesization), so the output matches the generated client's types exactly.
// It emits `<output>.responses.ts`: a `ResponseShapes` type mapping every
// operation to the TypeScript type of its primary JSON success body.
//
// Plain ESM so the CLI imports it under bare `node`. Authored in TypeScript you would write:
//
//   import { defineGenerator } from '@redocly/client-generator';
//   import { tsType } from '@redocly/client-generator/generate';
//   export default defineGenerator({ name: 'response-map', requires: ['sdk'], run({ model, outputPath }) { … } });
import { tsType } from '@redocly/client-generator/generate';

export default {
  name: 'response-map',
  requires: ['sdk'],
  run({ model, outputPath }) {
    // Every operation with a JSON success body — a 204 or an image download has no entry.
    const withJsonBody = model.services
      .flatMap((service) => service.operations)
      .flatMap((op) => {
        const success = op.successResponses.find((r) =>
          r.contentType.toLowerCase().includes('json')
        );
        return success ? [{ name: op.name, schema: success.schema }] : [];
      });

    const members = withJsonBody.map(
      ({ name, schema }) => `    ${name}: ${tsType(schema, 'string', '    ')};`
    );

    // `tsType` renders a `$ref` as a bare type reference, so the module
    // type-imports every referenced schema name from the generated client.
    const referenced = [...new Set(withJsonBody.flatMap(({ schema }) => refNames(schema)))].sort();
    const importLine =
      referenced.length > 0
        ? `import type { ${referenced.join(', ')} } from './client.js';\n\n`
        : '';

    return [
      {
        path: outputPath.replace(/\.ts$/, '.responses.ts'),
        content:
          '// Generated by the response-map custom generator. Do not edit by hand.\n' +
          importLine +
          `export type ResponseShapes = {\n${members.join('\n')}\n};` +
          '\n',
      },
    ];
  },
};

/** The named schemas a schema tree references (refs nested in arrays/objects/unions). */
function refNames(schema) {
  switch (schema.kind) {
    case 'ref':
      return [schema.name];
    case 'array':
      return refNames(schema.items);
    case 'object':
      return schema.properties.flatMap((property) => refNames(property.schema));
    case 'record':
      return refNames(schema.value);
    case 'union':
    case 'intersection':
      return schema.members.flatMap(refNames);
    default:
      return [];
  }
}
