// A custom generator (the experimental plugin API). Loaded by the `generators:` list in
// redocly.yaml as a path specifier, it runs alongside the built-in `sdk` and emits a
// `<output>.routes.ts` map of every operation — `<operationId>: 'METHOD /path'`.
//
// The output is built as a real TypeScript AST with the `@redocly/client-generator/generate`
// toolkit — the same `ts.factory` + printer the built-in generators use — so quoting and
// formatting come out right for free. Plain ESM so the CLI imports it under bare `node`.
// Authored in TypeScript you would write:
//
//   import { defineGenerator } from '@redocly/client-generator';
//   import { printStatements, ts } from '@redocly/client-generator/generate';
//   export default defineGenerator({ name: 'route-map', requires: ['sdk'], run({ model, outputPath }) { … } });
//
// `defineGenerator` is just an identity helper for types, so a plain object works too:
import { printStatements, ts } from '@redocly/client-generator/generate';

const { factory } = ts;

export default {
  name: 'route-map',
  requires: ['sdk'],
  run({ model, outputPath }) {
    const entries = model.services
      .flatMap((service) => service.operations)
      .map((op) =>
        factory.createPropertyAssignment(
          op.name,
          factory.createStringLiteral(`${op.method.toUpperCase()} ${op.path}`, true)
        )
      );
    // export const routes = { … } as const;
    const routes = factory.createVariableStatement(
      [factory.createModifier(ts.SyntaxKind.ExportKeyword)],
      factory.createVariableDeclarationList(
        [
          factory.createVariableDeclaration(
            'routes',
            undefined,
            undefined,
            factory.createAsExpression(
              factory.createObjectLiteralExpression(entries, true),
              factory.createTypeReferenceNode('const')
            )
          ),
        ],
        ts.NodeFlags.Const
      )
    );
    return [
      {
        path: outputPath.replace(/\.ts$/, '.routes.ts'),
        content:
          '// Generated by the route-map custom generator. Do not edit by hand.\n' +
          printStatements([routes]) +
          '\n',
      },
    ];
  },
};
